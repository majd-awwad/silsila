/** Word error rate for Arabic speech recognition: spelling variants and diacritics do not count as errors. */
export const normaliseArabic = (s: string) =>
  s.replace(/[ً-ٰٟـ]/g, '').replace(/[أإآ]/g, 'ا').replace(/ى/g, 'ي').replace(/ة/g, 'ه')
    .replace(/[^\p{L}\p{N}\s]/gu, ' ').replace(/\s+/g, ' ').trim();

export function wordErrorRate(reference: string, heard: string): number {
  const a = normaliseArabic(reference).split(' ').filter(Boolean);
  const b = normaliseArabic(heard).split(' ').filter(Boolean);
  if (!a.length) return b.length ? 1 : 0;
  let prev = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const row = [i];
    for (let j = 1; j <= b.length; j++) row[j] = Math.min(prev[j] + 1, row[j - 1] + 1, prev[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    prev = row;
  }
  return prev[b.length] / a.length;
}
